"use client";

import { useState } from "react";
import { ChevronDown } from "lucide-react";

type FaqItem = {
  id: string;
  question: string;
  answer: string;
};

const FAQ_ITEMS: FaqItem[] = [
  {
    id: "private-repos",
    question: "How does GitPilot access and protect private repositories?",
    answer:
      "When you connect your GitHub account, GitPilot requests standard scoped OAuth permissions. We clone the repository in ephemeral memory, parse AST chunks and calculate high-dimensional embeddings, and store only the vectors with metadata. Your source code is never permanently stored on our disks, and your code is never used to train public LLM models.",
  },
  {
    id: "ast-chunking",
    question: "Why is AST chunking superior to fixed-size token chunking?",
    answer:
      "Traditional RAG blindly chops files into 500-token chunks, often splitting a function definition in half or separating a class from its methods and docstrings. GitPilot parses real Abstract Syntax Trees (AST) using language-specific parsers (TypeScript, Python, Go, Rust, Java, C++), keeping functions, classes, and method scopes intact as complete semantic units.",
  },
  {
    id: "citations",
    question: "How do citations and verification work?",
    answer:
      "Every answer generated by GitPilot includes structured citations referencing the repository, file path, and start/end line numbers. You can click any citation pill to view the exact code snippet in context or jump directly to GitHub.",
  },
  {
    id: "pgvector-performance",
    question: "What powers the retrieval engine and how fast is it?",
    answer:
      "GitPilot uses PostgreSQL with the pgvector extension configured with HNSW (Hierarchical Navigable Small World) indexing. Sub-second vector similarity lookups run in under 40ms, even on large repositories containing hundreds of thousands of code chunks.",
  },
  {
    id: "self-hosting",
    question: "Can I self-host GitPilot in my own infrastructure?",
    answer:
      "Yes. GitPilot's backend is modular and containerized with Docker. You can point it to your self-hosted PostgreSQL instance with pgvector, bring your own OpenAI/Anthropic/Ollama API keys, and run behind your corporate VPN.",
  },
];

export function FaqSection() {
  const [openIds, setOpenIds] = useState<string[]>(["private-repos", "ast-chunking"]);

  const toggle = (id: string) => {
    setOpenIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  return (
    <div className="mx-auto w-full max-w-3xl space-y-3">
      {FAQ_ITEMS.map((item) => {
        const isOpen = openIds.includes(item.id);
        return (
          <div
            key={item.id}
            className="group rounded-xl border border-white/[0.08] bg-[#0c0d12]/70 backdrop-blur-md transition-all duration-300 hover:border-teal-500/40 hover:bg-[#0f1118]"
          >
            <button
              onClick={() => toggle(item.id)}
              className="flex w-full items-center justify-between px-5 py-4 text-left transition-colors cursor-pointer"
            >
              <span className="text-base font-medium text-zinc-200 group-hover:text-white flex items-center gap-2.5">
                <span className="size-1.5 rounded-full bg-teal-400 opacity-60 group-hover:opacity-100 transition-opacity" />
                {item.question}
              </span>
              <ChevronDown
                className={`size-4 text-zinc-400 transition-transform duration-300 ${
                  isOpen ? "rotate-180 text-teal-400" : ""
                }`}
              />
            </button>
            {isOpen && (
              <div className="border-t border-white/[0.04] px-5 py-4 text-sm leading-relaxed text-zinc-400">
                {item.answer}
              </div>
            )}
          </div>
        );
      })}
    </div>
  );
}
